/**
 * Retrieves a translated string for backend/server-side code.
 */
export function getBackendTranslation(key: string, locale?: string, params?: Record<string, string | number>): string {
  const norm = normalizeLocale(locale || 'en');
  const dict = BACKEND_DICTIONARIES[norm] || BACKEND_DICTIONARIES['en'];
  let text = dict[key] || BACKEND_DICTIONARIES['en'][key] || key;
  if (params && typeof text === 'string') {
    text = interpolateParams(text, params);
  }
  return text;
}
