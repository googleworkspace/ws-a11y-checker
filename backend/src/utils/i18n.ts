export const RTL_LANGUAGES = new Set(['ar', 'he', 'iw', 'fa', 'ur']);

/**
 * Checks if a given language or locale code is Right-to-Left.
 */
export function isRtlLocale(lang?: string): boolean {
  if (!lang || typeof lang !== 'string') return false;
  const clean = lang.trim().toLowerCase().split(/[-_]/)[0];
  return RTL_LANGUAGES.has(clean);
}

/**
 * Normalizes any locale code, alias, or BCP-47 tag to a canonical supported language code.
 */
export function normalizeLocale(locale?: string): string {
  if (!locale || typeof locale !== 'string') return 'en';
  const clean = locale.trim().replace(/_/g, '-').toLowerCase();

  // Hebrew aliases
  if (clean === 'iw' || clean === 'he' || clean.startsWith('iw-') || clean.startsWith('he-')) {
    return 'iw';
  }
  // Filipino / Tagalog aliases
  if (clean === 'tl' || clean === 'fil' || clean.startsWith('tl-') || clean.startsWith('fil-')) {
    return 'fil';
  }
  // Indonesian aliases
  if (clean === 'in' || clean === 'id' || clean.startsWith('in-') || clean.startsWith('id-')) {
    return 'id';
  }
  // Norwegian aliases
  if (clean === 'no' || clean === 'nb' || clean === 'nn' || clean.startsWith('nb-') || clean.startsWith('nn-') || clean.startsWith('no-')) {
    return 'no';
  }
  // Chinese variants
  if (
    clean === 'zh-cn' ||
    clean === 'zh-hans' ||
    clean.startsWith('zh-hans') ||
    clean.startsWith('zh-cn') ||
    clean === 'zh-sg' ||
    clean === 'zh'
  ) {
    return 'zh-CN';
  }
  if (
    clean === 'zh-tw' ||
    clean === 'zh-hant' ||
    clean.startsWith('zh-hant') ||
    clean.startsWith('zh-tw') ||
    clean.startsWith('zh-hk') ||
    clean.startsWith('zh-mo') ||
    clean === 'zh-hk' ||
    clean === 'zh-mo'
  ) {
    return 'zh-TW';
  }
  // Portuguese variants
  if (clean === 'pt-pt' || clean === 'pt-mz' || clean === 'pt-ao') {
    return 'pt-PT';
  }
  if (clean === 'pt-br' || clean === 'pt') {
    return 'pt-BR';
  }

  // Exact 2-letter matches and regional stripping
  const base = clean.split('-')[0];
  const supportedBases: Record<string, string> = {
    en: 'en', ar: 'ar', bn: 'bn', cs: 'cs', da: 'da', de: 'de',
    el: 'el', es: 'es', fa: 'fa', fi: 'fi', fr: 'fr', hi: 'hi',
    hu: 'hu', it: 'it', ja: 'ja', ko: 'ko', nl: 'nl', pl: 'pl',
    ro: 'ro', ru: 'ru', sv: 'sv', th: 'th', tr: 'tr', uk: 'uk',
    ur: 'ur', vi: 'vi'
  };

  if (supportedBases[base]) {
    return supportedBases[base];
  }

  return 'en';
}

/**
 * Resolves the effective language given a user preference and host workspace locale.
 */
export function resolveEffectiveLanguage(userPref?: string, hostLocale?: string): string {
  if (!userPref || userPref === 'AUTO') {
    return normalizeLocale(hostLocale || 'en');
  }
  return normalizeLocale(userPref);
}

/**
 * Interpolates parameters like {param} or {{param}} in text.
 */
export function interpolateParams(text: string, params?: Record<string, string | number>): string {
  if (!params || typeof text !== 'string') return text;
  let result = text;
  for (const [k, v] of Object.entries(params)) {
    const val = String(v ?? '');
    result = result.split(`{{${k}}}`).join(val);
    result = result.split(`{${k}}`).join(val);
  }
  return result;
}

